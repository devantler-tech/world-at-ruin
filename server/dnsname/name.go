// Package dnsname validates case-preserving ASCII DNS name grammar.
package dnsname

import "strings"

// Valid accepts one or more labels without changing case. Endpoint-specific
// policies such as IP rejection or requiring a dot belong to callers.
func Valid(name string) bool {
	if name == "" || len(name) > 253 {
		return false
	}
	for _, label := range strings.Split(name, ".") {
		if label == "" || len(label) > 63 || label[0] == '-' || label[len(label)-1] == '-' {
			return false
		}
		for _, char := range label {
			if (char < 'a' || char > 'z') && (char < 'A' || char > 'Z') && (char < '0' || char > '9') && char != '-' {
				return false
			}
		}
	}
	return true
}
